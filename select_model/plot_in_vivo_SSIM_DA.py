# =====================================================================
# 2. Load arrays
# =====================================================================

def load_array(
    path: Path,
    dtype=np.float64,
):

    if not path.exists():
        raise FileNotFoundError(
            f"Missing required metric file: {path}"
        )

    values = np.load(
        path,
        allow_pickle=False,
    )

    return np.asarray(
        values,
        dtype=dtype,
    ).reshape(-1)


# =====================================================================
# 3. Median filter
# =====================================================================

def median_filter_1d(
    values,
    window_size,
):

    values = np.asarray(
        values,
        dtype=np.float64,
    ).reshape(-1)

    if (
        window_size < 1
        or window_size % 2 == 0
    ):
        raise ValueError(
            "SSIM_MEDIAN_WINDOW must be a "
            "positive odd integer."
        )

    if not np.all(
        np.isfinite(values)
    ):
        raise ValueError(
            "SSIM-DA contains NaN or infinite values."
        )

    return median_filter(
        values,
        size=window_size,
        mode="nearest",
    )


# =====================================================================
# 4. Select maximum median-filtered SSIM-DA
# =====================================================================

def select_median_filtered_max(
    iterations,
    raw_values,
    start_iteration,
    end_iteration,
    metric_name,
):
    """
    Select the maximum median-filtered SSIM-DA
    inside the requested interval.

    Filtering is performed independently inside
    each selection interval.
    """

    iterations = np.asarray(
        iterations,
        dtype=np.int64,
    ).reshape(-1)

    raw_values = np.asarray(
        raw_values,
        dtype=np.float64,
    ).reshape(-1)

    if len(iterations) != len(raw_values):
        raise ValueError(
            f"{metric_name}: iterations and values "
            "have different lengths."
        )

    if (
        end_iteration is not None
        and end_iteration < start_iteration
    ):
        raise ValueError(
            f"{metric_name}: end iteration must "
            "be >= start iteration."
        )


    valid = (
        (iterations >= start_iteration)
        & np.isfinite(raw_values)
    )

    if end_iteration is not None:
        valid &= (
            iterations <= end_iteration
        )


    valid_indices = np.flatnonzero(
        valid
    )

    if valid_indices.size == 0:
        raise ValueError(
            f"No valid {metric_name} values "
            f"in interval "
            f"[{start_iteration}, {end_iteration}]."
        )


    interval_raw = (
        raw_values[valid_indices]
    )


    interval_filtered = (
        median_filter_1d(
            interval_raw,
            SSIM_MEDIAN_WINDOW,
        )
    )


    selected_local_index = int(
        np.argmax(
            interval_filtered
        )
    )


    selected_index = int(
        valid_indices[
            selected_local_index
        ]
    )


    return {

        "selected_index":
            selected_index,

        "selected_iteration":
            int(
                iterations[
                    selected_index
                ]
            ),

        "selected_raw_ssim_da":
            float(
                raw_values[
                    selected_index
                ]
            ),

        "selected_filtered_ssim_da":
            float(
                interval_filtered[
                    selected_local_index
                ]
            ),

        "selection_start_iteration":
            int(
                start_iteration
            ),

        "selection_end_iteration":
            (
                None
                if end_iteration is None
                else int(
                    end_iteration
                )
            ),
    }


# =====================================================================
# 5. Restrict display range
# =====================================================================

def restrict_iteration_range(
    iterations,
    arrays,
):

    keep = np.ones(
        len(iterations),
        dtype=bool,
    )


    if START_ITERATION is not None:

        keep &= (
            iterations
            >= START_ITERATION
        )


    if END_ITERATION is not None:

        keep &= (
            iterations
            <= END_ITERATION
        )


    if not np.any(keep):

        raise ValueError(
            "No data remain after applying "
            "the iteration range."
        )


    return (

        iterations[keep],

        {
            name:
                np.asarray(values)[keep]

            for name, values
            in arrays.items()
        },
    )


# =====================================================================
# 6. Helpers
# =====================================================================

def format_interval(
    start_iteration,
    end_iteration,
):

    end_text = (
        "end"
        if end_iteration is None
        else str(end_iteration)
    )

    return (
        f"{start_iteration}-{end_text}"
    )


def build_point(
    selection,
    label,
    color,
    size,
    zorder,
):

    return {

        "label":
            label,

        "iteration":
            selection[
                "selected_iteration"
            ],

        "raw_ssim_da":
            selection[
                "selected_raw_ssim_da"
            ],

        "filtered_ssim_da":
            selection[
                "selected_filtered_ssim_da"
            ],

        "start_iteration":
            selection[
                "selection_start_iteration"
            ],

        "end_iteration":
            selection[
                "selection_end_iteration"
            ],

        "color":
            color,

        "size":
            size,

        "zorder":
            zorder,
    }


def mark_point(
    ax,
    point,
):

    ax.scatter(

        [
            point[
                "iteration"
            ]
        ],

        [
            point[
                "filtered_ssim_da"
            ]
        ],

        s=point["size"],

        marker="o",

        facecolor=point["color"],

        edgecolor=POINT_EDGE_COLOR,

        linewidth=0.8,

        zorder=point["zorder"],

        label=point["label"],
    )


