# 7. Save selected checkpoints
# =====================================================================

def save_selection(
    save_dir,
    point,
):

    save_dir.mkdir(
        parents=True,
        exist_ok=True,
    )


    selected = np.asarray(
        [
            point[
                "iteration"
            ]
        ],
        dtype=np.int64,
    )


    np.save(
        save_dir
        / "selected_iteration.npy",
        selected,
    )

    np.save(
        save_dir
        / "selected_epoch.npy",
        selected,
    )


    lines = [

        f"Selection name = "
        f"{point['label']}",

        f"Selection interval = "
        f"[{point['start_iteration']}, "
        f"{point['end_iteration']}]",

        f"SSIM-DA median window = "
        f"{SSIM_MEDIAN_WINDOW}",

        "",

        f"Selected Iteration = "
        f"{point['iteration']}",

        f"Original SSIM-DA = "
        f"{point['raw_ssim_da']:.12g}",

        f"Median-filtered SSIM-DA = "
        f"{point['filtered_ssim_da']:.12g}",

        "",

        "Selection rule:",

        "Apply one median filter to SSIM-DA "
        "inside the configured interval and "
        "select the maximum of the filtered curve.",
    ]


    summary_path = (
        save_dir
        / "selection_summary.txt"
    )


    summary_path.write_text(
        "\n".join(lines) + "\n",
        encoding="utf-8",
    )


    print(
        f"[Saved] {summary_path}"
    )


# =====================================================================
# 8. X-axis formatting
# =====================================================================

def apply_iteration_axis(ax):

    """
    Format iterations as:

        0, 1, 2, ...

    with a ×10^4 multiplier.
    """

    if PLOT_XLIM is not None:

        xmin, xmax = (
            PLOT_XLIM
        )

        ax.set_xlim(
            xmin,
            xmax,
        )

    else:

        xmin, xmax = (
            ax.get_xlim()
        )


    first_tick = int(
        np.ceil(
            xmin
            / ITERATION_TICK_STEP
        )
        * ITERATION_TICK_STEP
    )


    last_tick = int(
        np.floor(
            xmax
            / ITERATION_TICK_STEP
        )
        * ITERATION_TICK_STEP
    )


    ticks = np.arange(
        first_tick,
        last_tick
        + ITERATION_TICK_STEP,
        ITERATION_TICK_STEP,
        dtype=np.int64,
    )


    if ticks.size > 0:

        ax.set_xticks(
            ticks
        )

        ax.set_xticklabels(
            [
                f"{tick / ITERATION_AXIS_SCALE:g}"
                for tick in ticks
            ]
        )

    else:

        ax.xaxis.set_major_locator(
            MaxNLocator(
                nbins=MAX_MAJOR_TICKS
            )
        )


    if SHOW_ITERATION_POWER_LABEL:

        ax.text(
            1.0,
            -0.115,
            r"$\times10^{4}$",

            transform=ax.transAxes,

            ha="right",
            va="top",

            fontsize=16,
        )


# =====================================================================
# 9. Figure formatting
# =====================================================================

def finish_axis(
    ax,
    title,
    ylabel,
):

    ax.set_title(
        title
    )

    ax.set_xlabel(
        "Iteration"
    )

    ax.set_ylabel(
        ylabel,
        color=SSIM_FILTERED_COLOR,
    )

    ax.grid(False)


    apply_iteration_axis(
        ax
    )


    if SSIM_YLIM is not None:

        ax.set_ylim(
            SSIM_YLIM[0],
            SSIM_YLIM[1],
        )


    ax.yaxis.set_major_locator(
        MaxNLocator(
            nbins=MAX_MAJOR_TICKS
        )
    )


    ax.tick_params(
        axis="x",
        direction="out",
        length=4,
        width=1,
        colors="black",
    )


    ax.tick_params(
        axis="y",
        direction="out",
        length=4,
        width=1,
        colors=SSIM_FILTERED_COLOR,
    )


    ax.spines[
        "left"
    ].set_color(
        "black"
    )

    ax.spines[
        "right"
    ].set_color(
        "black"
    )

    ax.spines[
        "top"
    ].set_color(
        "black"
    )

    ax.spines[
        "bottom"
    ].set_color(
        "black"
    )


    handles, labels = (
        ax.get_legend_handles_labels()
    )


    if handles:

        ax.legend(
            frameon=False,
            fontsize=10,
            loc=LEGEND_LOCATION,
        )


def save_figure(
    fig,
    filename,
):

    SAVE_FIG_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )


    save_path = (
        SAVE_FIG_DIR
        / f"{filename}.{FIG_FORMAT}"
    )


    fig.tight_layout()

    fig.subplots_adjust(
        bottom=0.18
    )


    fig.savefig(
        save_path,
        dpi=FIG_DPI,
        bbox_inches="tight",
    )


    plt.close(
        fig
    )


    print(
        f"[Saved] {save_path}"
    )


