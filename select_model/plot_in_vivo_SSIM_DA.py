# 10. Main
# =====================================================================

def main():

    SAVE_FIG_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )


    # -------------------------------------------------------------
    # Load SSIM-DA calculation results
    # -------------------------------------------------------------

    iterations_full = load_array(
        METRIC_DIR
        / "epochs.npy",
        dtype=np.int64,
    )


    raw_ssim_da_full = load_array(
        METRIC_DIR
        / "ssim_da.npy",
    )


    if len(iterations_full) == 0:

        raise ValueError(
            "epochs.npy is empty."
        )


    if (
        len(raw_ssim_da_full)
        != len(iterations_full)
    ):

        raise ValueError(
            "ssim_da.npy and epochs.npy "
            "have different lengths."
        )


    if np.any(
        np.diff(
            iterations_full
        ) <= 0
    ):

        raise ValueError(
            "epochs.npy must be "
            "strictly increasing."
        )


    print(
        "Loaded iterations :",
        len(iterations_full),
    )


    print(
        "SSIM-DA range     : "
        f"[{np.min(raw_ssim_da_full):.6f}, "
        f"{np.max(raw_ssim_da_full):.6f}]"
    )


    # -------------------------------------------------------------
    # Median-filtered SSIM-DA
    # -------------------------------------------------------------

    filtered_ssim_da_full = (
        median_filter_1d(
            raw_ssim_da_full,
            SSIM_MEDIAN_WINDOW,
        )
    )


    np.save(
        SAVE_FIG_DIR
        / f"{SSIM_FILTERED_KEY}.npy",

        filtered_ssim_da_full,
    )


    # -------------------------------------------------------------
    # Select maximum before 20000
    # -------------------------------------------------------------

    limited_selection = (
        select_median_filtered_max(

            iterations_full,

            raw_ssim_da_full,

            LIMITED_SSIM_SELECTION_START_ITERATION,

            LIMITED_SSIM_SELECTION_END_ITERATION,

            "limited-interval SSIM-DA",
        )
    )


    # -------------------------------------------------------------
    # Select global maximum
    # -------------------------------------------------------------

    global_selection = (
        select_median_filtered_max(

            iterations_full,

            raw_ssim_da_full,

            GLOBAL_SSIM_SELECTION_START_ITERATION,

            GLOBAL_SSIM_SELECTION_END_ITERATION,

            "global SSIM-DA",
        )
    )


    limited_interval_text = (
        format_interval(

            LIMITED_SSIM_SELECTION_START_ITERATION,

            LIMITED_SSIM_SELECTION_END_ITERATION,
        )
    )


    global_interval_text = (
        format_interval(

            GLOBAL_SSIM_SELECTION_START_ITERATION,

            GLOBAL_SSIM_SELECTION_END_ITERATION,
        )
    )


    # -------------------------------------------------------------
    # Points
    # -------------------------------------------------------------

    limited_point = build_point(

        limited_selection,

        label=(
            "SSIM-DA selection "
            f"({limited_interval_text})"
        ),

        color=LIMITED_SSIM_COLOR,

        size=85,

        zorder=9,
    )


    global_point = build_point(

        global_selection,

        label=(
            "SSIM-DA selection "
            f"({global_interval_text})"
        ),

        color=GLOBAL_SSIM_COLOR,

        size=70,

        zorder=10,
    )


    save_selection(
        LIMITED_SSIM_SELECTION_SAVE_DIR,
        limited_point,
    )


    save_selection(
        GLOBAL_SSIM_SELECTION_SAVE_DIR,
        global_point,
    )


    # -------------------------------------------------------------
    # Restrict plotting range
    # -------------------------------------------------------------

    iterations, arrays = (
        restrict_iteration_range(

            iterations_full,

            {
                SSIM_KEY:
                    raw_ssim_da_full,

                SSIM_FILTERED_KEY:
                    filtered_ssim_da_full,
            },
        )
    )


    # -------------------------------------------------------------
    # Plot
    # -------------------------------------------------------------

    fig, ax = plt.subplots(

        figsize=FIG_SIZE,

        dpi=FIG_CREATE_DPI,
    )


    # Raw SSIM-DA
    ax.plot(

        iterations,

        arrays[
            SSIM_KEY
        ],

        linewidth=1.0,

        color=SSIM_RAW_COLOR,

        alpha=0.45,

        label="Original SSIM-DA",
    )


    # Median-filtered SSIM-DA
    if PLOT_MEDIAN_FILTERED_SSIM:

        ax.plot(

            iterations,

            arrays[
                SSIM_FILTERED_KEY
            ],

            linewidth=LINE_WIDTH,

            color=SSIM_FILTERED_COLOR,

            label=(
                "Median-filtered SSIM-DA"
            ),
        )


    # Selection points
    mark_point(
        ax,
        limited_point,
    )

    mark_point(
        ax,
        global_point,
    )


    finish_axis(
        ax,
        TITLE_TEXT,
        Y_AXIS_LABEL,
    )


    save_figure(
        fig,
        "01_SSIM_DA",
    )


    # -------------------------------------------------------------
    # Print
    # -------------------------------------------------------------

    print(
        "\n"
        "================ "
        "In-vivo SSIM-DA selection "
        "================"
    )


    for point in (
        limited_point,
        global_point,
    ):

        print(
            f"\n{point['label']}"
        )

        print(
            f"  Iteration: "
            f"{point['iteration']}"
        )

        print(
            f"  Original SSIM-DA: "
            f"{point['raw_ssim_da']:.10g}"
        )

        print(
            f"  Median-filtered SSIM-DA: "
            f"{point['filtered_ssim_da']:.10g}"
        )


    if (
        limited_point[
            "iteration"
        ]
        ==
        global_point[
            "iteration"
        ]
    ):

        print(
            "\n[Notice] "
            "The blue and yellow points "
            "occur at the same iteration."
        )


    print(
        "\nFigure saved to:"
    )

    print(
        SAVE_FIG_DIR
        / f"01_SSIM_DA.{FIG_FORMAT}"
    )


if __name__ == "__main__":
    main()
